package main

import (
	"encoding/json"
	"fmt"
	"log/slog"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"

	"golang.org/x/text/cases"
	"golang.org/x/text/language"
)

var caser = cases.Title(language.English)

type FontJSON map[string]json.RawMessage

func main() {
	configMap := map[string]string{}
	{
		contents, err := os.ReadFile("config.sh")
		if err != nil {
			slog.Error("failed to read config.sh", "err", err)
			os.Exit(1)
		}

		lines := strings.Split(string(contents), "\n")
		for _, line := range lines {
			if strings.Contains(line, "=") {
				parts := strings.SplitN(line, "=", 2)
				if len(parts) == 2 {
					configMap[parts[0]] = parts[1]
				}
			}
		}
	}
	slog.Info("config.sh loaded", "configMap", configMap)

	var fontNames []string
	fontNameToIconNameMap := map[string][]string{}
	{
		files, err := filepath.Glob("bin/repo/" + configMap["REPO_DIRECTORY"] + "/*")
		if err != nil {
			slog.Error("failed to glob directories", "err", err)
			os.Exit(1)
		}
		for _, file := range files {
			fontName := filepath.Base(file)
			fontNames = append(fontNames, fontName)
		}
		slices.Sort(fontNames)

		for _, fontName := range fontNames {
			files, err := filepath.Glob("bin/repo/" + configMap["REPO_DIRECTORY"] + "/" + fontName + "/*.svg")
			if err != nil {
				slog.Error("failed to glob icons", "err", err)
				os.Exit(1)
			}
			for _, file := range files {
				iconName := filepath.Base(file)
				iconName = strings.TrimSuffix(iconName, ".svg")
				fontNameToIconNameMap[fontName] = append(fontNameToIconNameMap[fontName], iconName)
			}
			slices.Sort(fontNameToIconNameMap[fontName])
		}
	}

	constantMap := map[string]string{}
	constantGroupMap := map[string][]string{}

	for _, fontName := range fontNames {
		slog.Info("Font", "fontName", fontName, "icons", len(fontNameToIconNameMap[fontName]))

		for _, name := range fontNameToIconNameMap[fontName] {
			prettyName := "Icon" + makePretty(fontName+"-"+name)
			slog.Info("pretty name", "prettyName", prettyName)
			constantMap[prettyName] = "fa-" + fontName + " fa-" + name
			constantGroupMap["Icon"] = append(constantGroupMap["Icon"], prettyName)
			constantGroupMap["Icon"+makePretty(fontName)] = append(constantGroupMap["Icon"+makePretty(fontName)], prettyName)
		}
	}

	{
		constantNames := []string{}
		for prettyName := range constantMap {
			constantNames = append(constantNames, prettyName)
		}
		sort.Strings(constantNames)

		constantGroupNames := []string{}
		for constantGroupName := range constantGroupMap {
			constantGroupNames = append(constantGroupNames, constantGroupName)
		}
		sort.Strings(constantGroupNames)
		slog.Info("Constant group names", "constantGroupNames", constantGroupNames)

		builder := strings.Builder{}
		builder.WriteString("package fontawesome\n")
		builder.WriteString("\n")
		builder.WriteString("// This file is generated by generate-constants.go. Do not edit.\n")
		builder.WriteString("\n")
		builder.WriteString("const (\n")
		for _, constantName := range constantNames {
			constantValue := constantMap[constantName]
			builder.WriteString(fmt.Sprintf("	%s = \"%s\"\n", constantName, constantValue))
		}
		builder.WriteString(")\n")
		for _, constantGroupName := range constantGroupNames {
			builder.WriteString("// ")
			builder.WriteString(constantGroupName)
			builder.WriteString(" returns all of the available ")
			builder.WriteString(constantGroupName)
			builder.WriteString(" icons.\n")
			builder.WriteString("func ")
			builder.WriteString(constantGroupName)
			builder.WriteString("() []string {\n")
			builder.WriteString("\treturn []string{\n")
			var constantNames []string
			for _, constantName := range constantGroupMap[constantGroupName] {
				constantNames = append(constantNames, constantName)
			}
			sort.Strings(constantNames)
			for _, constantName := range constantNames {
				builder.WriteString("\t")
				builder.WriteString(constantName)
				builder.WriteString(",\n")
			}
			builder.WriteString("\t}\n")
			builder.WriteString("}\n")
			builder.WriteString("\n")
		}

		contents := builder.String()
		err := os.WriteFile("constants.go", []byte(contents), 0644)
		if err != nil {
			slog.Error("failed to write constants.go", "err", err)
			os.Exit(1)
		}
	}
}

func makePretty(name string) string {
	parts := strings.Split(name, "-")
	for i, part := range parts {
		parts[i] = caser.String(part)
	}
	return strings.Join(parts, "")
}
